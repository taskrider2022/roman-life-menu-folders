import os, json, sys
sys.path.insert(0, os.path.dirname(__file__))
from gather import data, MODS, SELF
from analyze import info
from collections import OrderedDict, defaultdict
from xml.sax.saxutils import escape, quoteattr
from PIL import Image, ImageDraw, ImageFont, ImageFilter

OUT = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "mod")
if "--out" in sys.argv:
    OUT = sys.argv[sys.argv.index("--out") + 1]
PRIO = ["latium", "albion", "imperial", "celtic", "other"]
CAT_ORDER = ["Food", "Culture", "Fashion", "Household", "Wonder", None]
NAMES = {"latium": "Roman Life - Latium", "albion": "Roman Life - Albion", "imperial": "Roman Life - Imperial",
         "celtic": "Celtic Independence", "other": "Weitere Mods"}
import guidrange
FIRST_GUID = guidrange.FIRST_FOLDER_GUID  # (latium, 41364) takes the first GUID

mod_of = {}
mod_need = {}
for (fam, cat), items in data.items():
    for b, conds, mid in items:
        mod_of[b] = mid
        n = info(b)[0]
        if n and fam in ("latium", "albion", "imperial"):
            mod_need[mid] = n

def sort_key(b):
    n, ctx, amt = info(b)
    n = n or mod_need.get(mod_of.get(b))
    return (CAT_ORDER.index(n) if n in CAT_ORDER else len(CAT_ORDER),
            int(ctx) if ctx else 9999, amt if amt is not None else 10**9, int(b))

# building -> category -> first family by priority; collect condition variants
variants = defaultdict(lambda: defaultdict(list))  # (cat,building) -> fam -> [conds,...]
mods = set()
celtic_items = {b for (fam, cat), items in data.items() for b, conds, mid in items if "celtic" in mid}
for (fam, cat), items in data.items():
    for b, conds, mid in items:
        if fam not in ("latium", "albion", "imperial"):
            continue
        mods.add(mid)
        v = variants[(cat, b)][fam]
        if conds not in v:
            v.append(conds)

folders = OrderedDict()  # (fam, cat) -> {building: [cond variants]}
for (cat, b), byfam in variants.items():
    fam = "albion" if cat in ("41327", "41328", "41329", "41330", "41331") else "latium"
    allv = []
    for f in PRIO:
        for c in byfam.get(f, []):
            if c not in allv:
                allv.append(c)
    folders.setdefault((fam, cat), OrderedDict())[b] = allv

folders = OrderedDict((k, v) for k, v in folders.items() if len(v) >= 1)
keys = sorted(folders, key=lambda k: (k[1], PRIO.index(k[0])))
guid_of = {}
nxt = FIRST_GUID + 1
for k in keys:
    if k == ("latium", "41364"):
        guid_of[k] = FIRST_GUID
    else:
        guid_of[k] = nxt
        nxt += 1

def wrap(conds, inner):
    out = inner
    for c in reversed(conds or []):
        out = f'  <Group Condition={quoteattr(c)}>\n{out}\n  </Group>'
    return out

L = ['<?xml version="1.0" encoding="utf-8"?>', "<ModOps>", ""]
L.append(f"  <!-- Generated by gen.py. Folder GUIDs {guidrange.RANGE_START}+ (registered range). -->")
for k in keys:
    fam, cat = k
    g = guid_of[k]
    L.append(f'''  <ModOp Type="addNextSibling" GUID="{cat}">
    <Asset>
      <Template>ConstructionCategory</Template>
      <Values>
        <Standard>
          <GUID>{g}</GUID>
          <Name>MenuFolder_{fam}_{cat}</Name>
          <IconFilename>data/roman-life-menu-folders-gammelflei/ui/folder_{fam}.png</IconFilename>
        </Standard>
        <ConstructionCategory>
          <BuildingList></BuildingList>
        </ConstructionCategory>
        <Text>
          <OasisId>{g}</OasisId>
        </Text>
        <Locked>
          <DefaultLockedState>0</DefaultLockedState>
        </Locked>
      </Values>
    </Asset>
  </ModOp>
  <ModOp Type="add" GUID="{cat}" Path="/Values/ConstructionCategory/BuildingList">
    <Item><Building>{g}</Building></Item>
  </ModOp>
''')
for k in keys:
    fam, cat = k
    g = guid_of[k]
    for b in sorted(folders[k], key=sort_key):
        variants_ = folders[k][b]
        for conds in variants_:
            inner = f'''    <ModOp Type="remove" GUID="{cat}" Path="/Values/ConstructionCategory/BuildingList/Item[Building='{b}']" />
    <ModOp Type="remove" GUID="{g}" Path="/Values/ConstructionCategory/BuildingList/Item[Building='{b}']" />
    <ModOp Type="add" GUID="{g}" Path="/Values/ConstructionCategory/BuildingList"><Item><Building>{b}</Building></Item></ModOp>'''
            L.append(wrap(conds, inner) if conds else inner)
L.append("</ModOps>")

exp = os.path.join(OUT, "data", "base", "config", "export")
os.makedirs(exp, exist_ok=True)
open(os.path.join(exp, "assets.xml"), "w", encoding="utf-8").write("\n".join(L) + "\n")

texts = "\n".join(f"    <Text><LineId>{guid_of[k]}</LineId><Text>{NAMES[k[0]]}</Text></Text>" for k in keys)
tx = f'<?xml version="1.0" encoding="utf-8"?>\n<ModOps>\n  <ModOp Add="//TextExport/Texts">\n{texts}\n  </ModOp>\n</ModOps>\n'
gui = os.path.join(OUT, "data", "base", "config", "gui")
for lang in ("english", "german"):
    open(os.path.join(gui, f"texts_{lang}.xml"), "w", encoding="utf-8").write(tx)

mi = json.load(open(os.path.join(OUT, "modinfo.json"), encoding="utf-8"))
extra = {"rl-latium-khayi", "rl-albion-khayi", "rl-shared-khayi"}
mi["Dependencies"]["LoadAfter"] = sorted(mods | extra)
mi["Version"] = "0.5.0"
mi["ModID"] = "roman-life-menu-folders-gammelflei"
mi["ModName"] = {"English": "Roman Life Menu Folders", "German": "Roman Life Baumenü-Ordner"}
mi["Description"] = {
    "English": "Moves the Roman Life items (Latium, Albion, Imperial) out of the flat construction menu into one folder per population tier.",
    "German": "Verschiebt die Roman-Life-Gebäude (Latium, Albion, Imperial) aus dem flachen Baumenü in je einen Ordner pro Bevölkerungsstufe.",
}
json.dump(mi, open(os.path.join(OUT, "modinfo.json"), "w", encoding="utf-8"), indent=2, ensure_ascii=False)

# icons
import icons
icons.build(os.path.join(OUT, "data", "roman-life-menu-folders-gammelflei", "ui"))

tot = sum(len(v) for v in folders.values())
print("folders", len(keys), "buildings", tot)
for k in keys:
    print(k, guid_of[k], len(folders[k]))
